//! Generates src/webp_tables.rs from the text of RFC 6386 (VP8 Data Format and Decoding Guide).
//!
//! The VP8 decoder needs a few thousand constants: token probabilities, their update
//! probabilities, subblock mode probabilities, and the dequantization tables. They are taken
//! from the standard itself rather than typed in, and each table that the RFC prints twice (in
//! the text and in its reference decoder) is checked against its second copy.
//!
//!     curl -o rfc6386.txt https://www.rfc-editor.org/rfc/rfc6386.txt
//!     rustc --edition 2021 -O tools/vp8_tables.rs -o /tmp/vp8_tables
//!     /tmp/vp8_tables rfc6386.txt > src/webp_tables.rs

use std::fmt::Write as _;

/// The integers of the initializer that follows the line naming `name`, with the RFC's page
/// headers and footers and C comments left out.
fn table(text: &str, name: &str, from: usize) -> Vec<u32> {
    let lines: Vec<&str> = text.lines().collect();
    let start = lines.iter().enumerate().skip(from).find(|(_, line)| line.contains(name) && !line.trim_start().starts_with("/*")).map(|(index, _)| index).unwrap_or_else(|| panic!("{name} not found"));
    let mut body = String::new();
    for line in &lines[start..] {
        let trimmed = line.trim_start();
        if trimmed.starts_with("Bankoski, et al.") || trimmed.starts_with("RFC 6386") || trimmed.contains('\u{c}') {
            continue;
        }
        body.push_str(line);
        body.push('\n');
        if body.contains("};") {
            break;
        }
    }
    let body = &body[body.find('=').expect("an initializer") + 1..];
    let mut cleaned = String::new();
    let mut rest = body;
    while let Some(open) = rest.find("/*") {
        cleaned.push_str(&rest[..open]);
        rest = &rest[open + rest[open..].find("*/").expect("closed comment") + 2..];
    }
    cleaned.push_str(rest);
    let end = cleaned.find("};").expect("end of table");
    cleaned[..end].split(|c: char| !c.is_ascii_digit()).filter(|part| !part.is_empty()).map(|part| part.parse().unwrap()).collect()
}

fn line_of(text: &str, needle: &str) -> usize {
    text.lines().position(|line| line.contains(needle)).unwrap_or_else(|| panic!("{needle} not found"))
}

fn emit(out: &mut String, name: &str, kind: &str, dims: &[usize], values: &[u32]) {
    let total: usize = dims.iter().product();
    assert_eq!(values.len(), total, "{name}: {} values, expected {total}", values.len());
    let shape = dims.iter().rev().fold(kind.to_string(), |inner, dim| format!("[{inner}; {dim}]"));
    let _ = writeln!(out, "pub const {name}: {shape} = {};\n", nest(values, dims));
}

fn nest(values: &[u32], dims: &[usize]) -> String {
    if dims.len() == 1 {
        return format!("[{}]", values.iter().map(u32::to_string).collect::<Vec<_>>().join(", "));
    }
    let step: usize = dims[1..].iter().product();
    let parts: Vec<String> = values.chunks(step).map(|chunk| nest(chunk, &dims[1..])).collect();
    format!("[\n{}\n]", parts.join(",\n"))
}

fn main() {
    let path = std::env::args().nth(1).expect("the path of rfc6386.txt");
    let text = std::fs::read_to_string(path).expect("readable RFC text");
    let update = table(&text, "const Prob coeff_update_probs [4] [8] [3]", 0);
    let defaults = table(&text, "const Prob default_coeff_probs [4] [8] [3]", 0);
    let reference_defaults = table(&text, "k_default_coeff_probs [BLOCK_TYPES][COEFF_BANDS]", 0);
    assert_eq!(defaults, reference_defaults, "the two copies of the default token probabilities differ");
    let reference_update = table(&text, "k_coeff_entropy_update_probs", line_of(&text, "unsigned char k_coeff_entropy_update_probs[BLOCK_TYPES]"));
    assert_eq!(update, reference_update, "the two copies of the update probabilities differ");
    let bmode = table(&text, "const Prob kf_bmode_prob [num_intra_bmodes] [num_intra_bmodes]", line_of(&text, "11.5.  Subblock Mode Probability Table"));
    let dc = table(&text, "static const int dc_qlookup[QINDEX_RANGE]", 0);
    let ac = table(&text, "static const int ac_qlookup[QINDEX_RANGE]", 0);
    let mut out = String::from("//! VP8 constants from RFC 6386, generated by tools/vp8_tables.rs; do not edit by hand.\n\n");
    emit(&mut out, "COEFF_UPDATE_PROBS", "u8", &[4, 8, 3, 11], &update);
    emit(&mut out, "DEFAULT_COEFF_PROBS", "u8", &[4, 8, 3, 11], &defaults);
    emit(&mut out, "KF_BMODE_PROBS", "u8", &[10, 10, 9], &bmode);
    emit(&mut out, "DC_QLOOKUP", "i32", &[128], &dc);
    emit(&mut out, "AC_QLOOKUP", "i32", &[128], &ac);
    print!("{out}");
}
